DO $$
DECLARE
    v_invalidas BOOLEAN;
BEGIN
    SELECT EXISTS (SELECT 1 FROM public.cuentas t WHERE NOT EXISTS (
        SELECT 1 FROM public.municipios m
        WHERE m.nombre_estado = t.estado_perfil_ubi AND m.nombre_municipio = t.municipio_perfil_ubi))
    INTO v_invalidas;
    IF v_invalidas THEN
        RAISE NOTICE 'fk_cuentas_municipios queda NOT VALID: hay cuentas con ubicación fuera del catálogo.';
    ELSE
        ALTER TABLE public.cuentas VALIDATE CONSTRAINT fk_cuentas_municipios;
    END IF;

    SELECT EXISTS (SELECT 1 FROM public.publicaciones t WHERE t.estado_ubicacion IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.municipios m
        WHERE m.nombre_estado = t.estado_ubicacion AND m.nombre_municipio = t.municipio_ubicacion))
    INTO v_invalidas;
