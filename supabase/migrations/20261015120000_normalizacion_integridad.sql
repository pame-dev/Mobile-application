-- ── 1. Administrador a partir de cualquier cuenta ───────────────────────────
-- Ser admin es un rol extra: la cuenta conserva su tipo (particular o lote).
DROP TRIGGER IF EXISTS trg_cuentas_roles_validar_admin ON public.cuentas_roles;
DROP FUNCTION IF EXISTS public.fn_cuentas_roles_validar_admin();


-- ── 2. Limpieza de ubicaciones ──────────────────────────────────────────────
-- "Torreon" sin acento y Torreón con un estado equivocado (Torreón está en Coahuila).
UPDATE public.cuentas SET municipio_perfil_ubi = 'Torreón' WHERE municipio_perfil_ubi = 'Torreon';
UPDATE public.cuentas SET estado_perfil_ubi = 'Coahuila'
WHERE municipio_perfil_ubi = 'Torreón' AND estado_perfil_ubi <> 'Coahuila';
-- Cuenta del equipo (Nancy) con estado y municipio invertidos; se regresa al valor del alta.
UPDATE public.cuentas SET estado_perfil_ubi = 'Coahuila', municipio_perfil_ubi = 'Torreón'
WHERE id_cuenta = '00000000-0000-0000-0000-000000000002'
  AND estado_perfil_ubi = 'Tap' AND municipio_perfil_ubi = 'Coahuila';

UPDATE public.publicaciones SET municipio_ubicacion = 'Torreón' WHERE municipio_ubicacion = 'Torreon';
UPDATE public.publicaciones SET estado_ubicacion = 'Coahuila'
WHERE municipio_ubicacion = 'Torreón' AND estado_ubicacion <> 'Coahuila';
UPDATE public.propuestas_publicacion SET municipio_ubicacion = 'Torreón' WHERE municipio_ubicacion = 'Torreon';
UPDATE public.propuestas_publicacion SET estado_ubicacion = 'Coahuila'
WHERE municipio_ubicacion = 'Torreón' AND estado_ubicacion <> 'Coahuila';


-- ── 3. Catálogo de estados y municipios ─────────────────────────────────────
CREATE TABLE public.estados (
    nombre_estado VARCHAR(60) PRIMARY KEY,
    CONSTRAINT chk_estados_nombre CHECK (CHAR_LENGTH(TRIM(nombre_estado)) > 0)
);
COMMENT ON TABLE public.estados IS 'Estados de México (mismo catálogo que el selector de la app).';

CREATE TABLE public.municipios (
    nombre_estado    VARCHAR(60)  NOT NULL,
    nombre_municipio VARCHAR(100) NOT NULL,
    CONSTRAINT pk_municipios PRIMARY KEY (nombre_estado, nombre_municipio),
    CONSTRAINT fk_municipios_estados FOREIGN KEY (nombre_estado)
        REFERENCES public.estados (nombre_estado) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_municipios_nombre CHECK (CHAR_LENGTH(TRIM(nombre_municipio)) > 0)
);
COMMENT ON TABLE public.municipios IS 'Municipios de cada estado (mismo catálogo que el selector de la app).';

