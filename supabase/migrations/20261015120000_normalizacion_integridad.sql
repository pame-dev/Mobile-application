-- ── 8. Triggers de integridad ───────────────────────────────────────────────

-- El año no puede pasar del año que entra (modelos del próximo año sí).
CREATE FUNCTION public.fn_validar_anio_vehiculo()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
    v_maximo INT := EXTRACT(YEAR FROM NOW())::INT + 1;
BEGIN
    IF NEW.anio > v_maximo THEN
        RAISE EXCEPTION 'El año del vehículo no puede ser mayor a %.', v_maximo;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_propuestas_validar_anio
    BEFORE INSERT OR UPDATE OF anio ON public.propuestas_publicacion
    FOR EACH ROW EXECUTE FUNCTION public.fn_validar_anio_vehiculo();

-- Nadie reporta su propia publicación (la app ya oculta el botón al dueño).
CREATE FUNCTION public.fn_reportes_no_propios()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM public.publicaciones
        WHERE id_publicacion = NEW.id_publicacion AND id_propietario = NEW.id_reportante
    ) THEN
        RAISE EXCEPTION 'No puedes reportar tu propia publicación.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reportes_no_propios
    BEFORE INSERT OR UPDATE OF id_publicacion, id_reportante ON public.reportes
    FOR EACH ROW EXECUTE FUNCTION public.fn_reportes_no_propios();

-- Toda cuenta lote tiene su perfil de lote. Se revisa al terminar la transacción
-- porque el registro inserta primero la cuenta y luego el perfil.
CREATE FUNCTION public.fn_lote_requiere_perfil()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
    v_id UUID := CASE WHEN TG_TABLE_NAME = 'cuentas' THEN NEW.id_cuenta ELSE OLD.id_cuenta END;
BEGIN
    IF EXISTS (SELECT 1 FROM public.cuentas WHERE id_cuenta = v_id AND tipo_cuenta = 'lote')
       AND NOT EXISTS (SELECT 1 FROM public.perfiles_lote WHERE id_cuenta = v_id) THEN
        RAISE EXCEPTION 'Una cuenta de tipo lote necesita su perfil de lote (dirección).';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_cuentas_lote_requiere_perfil
    AFTER INSERT ON public.cuentas
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.fn_lote_requiere_perfil();

CREATE CONSTRAINT TRIGGER trg_perfiles_lote_no_borrar
    AFTER DELETE ON public.perfiles_lote
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION public.fn_lote_requiere_perfil();


